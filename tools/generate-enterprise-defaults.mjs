#!/usr/bin/env node
/**
 * Bake packager-machine GENOFFICE_AI_* / BOCHA_API_KEY into
 * packages/ai-provider/src/enterprise-defaults.generated.ts so a packaged
 * Electron app resolves custom chat/media and Bocha search credentials
 * without inheriting the packager's shell env at double-click.
 *
 * Wired from:
 *   - root `build` / `build:all` (and therefore `dist:mac|win|linux`)
 *   - `@genoffice/shell` `prebuild` / `dist:*` (`npm run build && electron-builder`)
 *
 * `npm run dev` and test/typecheck use `--empty` so local development still
 * reads process.env from the shell and unit tests stay isolated.
 *
 * Export these before `npm run dist:mac|win|linux` (or `npm run build:all`):
 *   GENOFFICE_AI_BASE_URL
 *   GENOFFICE_AI_API_KEY
 *   GENOFFICE_AI_MODEL
 *   GENOFFICE_AI_MEDIA_BASE_URL / GENOFFICE_AI_MEDIA_API_KEY  (optional; runtime
 *     falls back to the chat URL/key)
 *   GENOFFICE_AI_IMAGE_MODEL / GENOFFICE_AI_ANALYSIS_MODEL / GENOFFICE_AI_VIDEO_MODEL
 *     (optional; prefills Custom media model ids when Settings has none.
 *     VIDEO_MODEL falls back to ANALYSIS_MODEL at overlay time if unset)
 *   GENOFFICE_AI_SEARCH_API_KEY or BOCHA_API_KEY
 *
 * `apps/shell/electron-builder.env` is loaded by electron-builder only, after
 * electron-vite has already bundled this module — putting keys there is too
 * late. They must be in the process environment before the dist command.
 *
 * Security: baked values are extractable from the asar / app resources.
 * Internal distribution only. Never commit the generated file.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const DEFAULT_OUT = join(ROOT, 'packages/ai-provider/src/enterprise-defaults.generated.ts')

const KEYS = [
  'GENOFFICE_AI_BASE_URL',
  'GENOFFICE_AI_API_KEY',
  'GENOFFICE_AI_MODEL',
  'GENOFFICE_AI_MEDIA_BASE_URL',
  'GENOFFICE_AI_MEDIA_API_KEY',
  'GENOFFICE_AI_IMAGE_MODEL',
  'GENOFFICE_AI_ANALYSIS_MODEL',
  'GENOFFICE_AI_VIDEO_MODEL',
  'GENOFFICE_AI_SEARCH_API_KEY',
  'BOCHA_API_KEY',
]

/** Unicode dashes (NB hyphen, en/em dash, minus, fullwidth) → ASCII '-' so ids like qwen3‑vl match the API. */
const MODEL_KEYS = new Set([
  'GENOFFICE_AI_MODEL',
  'GENOFFICE_AI_IMAGE_MODEL',
  'GENOFFICE_AI_ANALYSIS_MODEL',
  'GENOFFICE_AI_VIDEO_MODEL',
])

function normalizeModelId(value) {
  return value.replace(/[\u2010-\u2015\u2212\uFE58\uFE63\uFF0D]/g, '-')
}

function parseArgs(argv) {
  const out = { empty: false, outPath: DEFAULT_OUT }
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i]
    if (arg === '--empty') out.empty = true
    else if (arg === '--out') {
      const next = argv[++i]
      if (!next) throw new Error('generate-enterprise-defaults: --out requires a path')
      out.outPath = next
    } else if (arg === '--help' || arg === '-h') {
      out.help = true
    } else {
      throw new Error(`generate-enterprise-defaults: unknown argument ${arg}`)
    }
  }
  return out
}

function readValue(empty, name) {
  if (empty) return ''
  const raw = process.env[name]?.trim() ?? ''
  return MODEL_KEYS.has(name) ? normalizeModelId(raw) : raw
}

function renderModule(values) {
  const fields = KEYS.map((key) => `  ${key}: ${JSON.stringify(values[key])},`).join('\n')
  return `/**
 * AUTO-GENERATED by tools/generate-enterprise-defaults.mjs — do not edit.
 * Packagers: export GENOFFICE_AI_* / BOCHA_API_KEY before \`npm run dist:*\`.
 * This file is gitignored and may contain secrets. Internal distribution only.
 */
import type { EnterpriseAiBuildDefaults } from './enterprise-defaults'

export const ENTERPRISE_AI_BUILD_DEFAULTS = {
${fields}
} as const satisfies EnterpriseAiBuildDefaults
`
}

function main(argv = process.argv.slice(2)) {
  const args = parseArgs(argv)
  if (args.help) {
    process.stdout.write(
      'Usage: node tools/generate-enterprise-defaults.mjs [--empty] [--out path]\n',
    )
    return { outPath: args.outPath, baked: [], wrote: false }
  }

  const values = Object.fromEntries(KEYS.map((key) => [key, readValue(args.empty, key)]))
  const baked = KEYS.filter((key) => values[key] !== '')
  const source = renderModule(values)

  mkdirSync(dirname(args.outPath), { recursive: true })
  let previous = ''
  try {
    previous = readFileSync(args.outPath, 'utf8')
  } catch {
    /* first run */
  }
  const wrote = previous !== source
  if (wrote) writeFileSync(args.outPath, source)

  const mode = args.empty
    ? 'empty'
    : baked.length
      ? `baked ${baked.join(', ')}`
      : 'empty (no env set)'
  process.stdout.write(`generate-enterprise-defaults: ${mode} → ${args.outPath}\n`)
  return { outPath: args.outPath, baked, wrote }
}

const isMain =
  Boolean(process.argv[1]) && resolve(process.argv[1]) === fileURLToPath(import.meta.url)
if (isMain) {
  try {
    main()
  } catch (err) {
    process.stderr.write(`${err instanceof Error ? err.message : err}\n`)
    process.exit(1)
  }
}

export { KEYS, main, renderModule }
